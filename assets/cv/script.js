// Function to apply language
function applyLanguage(lang) {
    const langConfig = translations[lang] || translations['en'];
    const dir = langConfig.dir || 'ltr';

    // Keep <html> in sync too - search engines, screen readers and browser
    // translation all read lang/dir from the root element, not from <body>.
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;

    bodyElement.dir = dir;
    bodyElement.lang = lang;

    // The navbar itself is dir="ltr"-locked in the HTML (see <nav>) so its
    // buttons stay in a fixed position across languages - only the label
    // text inside them changes. Do not override that per-language here.

    if (lang === 'ar') {
        bodyElement.style.fontFamily = "'IBM Plex Sans Arabic', sans-serif";
    } else {
        bodyElement.style.fontFamily = "'Inter', sans-serif";
    }
    
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (langConfig[key]) {
            element.textContent = langConfig[key];
        }
    });
    
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (langConfig[key]) {
            element.placeholder = langConfig[key];
        }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(element => {
        const key = element.getAttribute('data-i18n-aria');
        if (langConfig[key]) {
            element.setAttribute('aria-label', langConfig[key]);
        }
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(element => {
        const key = element.getAttribute('data-i18n-alt');
        if (langConfig[key]) {
            element.alt = langConfig[key];
        }
    });

    // Page title and meta description are what search results and shared
    // links actually display, so they follow the selected language too.
    if (langConfig.pageTitle) {
        document.title = langConfig.pageTitle;
    }
    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription && langConfig.metaDescription) {
        metaDescription.setAttribute('content', langConfig.metaDescription);
    }
    
    langButtons.forEach(btn => {
        const isActive = btn.getAttribute('data-lang') === lang;
        btn.classList.toggle('active', isActive);
        btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
    
    const copyrightElement = document.getElementById('copyright');
    if (copyrightElement && langConfig.copyright) {
        copyrightElement.textContent = langConfig.copyright.replace('{year}', new Date().getFullYear());
    }
    
    localStorage.setItem('selectedLang', lang);
    currentLang = lang;
}

// Setup event listeners
function setupEventListeners() {
    // Language buttons
    langButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.getAttribute('data-lang');
            if (lang !== currentLang) {
                applyLanguage(lang);
            }
        });
    });
    
    // Smooth scrolling for all anchor links
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            e.preventDefault();
            
            const targetId = this.getAttribute('href');
            if (targetId === '#') return;
            
            const targetElement = document.querySelector(targetId);
            if (targetElement) {
                // Calculate offset for fixed header
                const offset = 80;
                
                window.scrollTo({
                    top: targetElement.offsetTop - offset,
                    behavior: 'smooth'
                });
                
                // Update active nav link
                updateActiveNavLink(targetId.substring(1));
                
                // Close mobile menu if open
                if (mobileMenu && !mobileMenu.classList.contains('hidden')) {
                    mobileMenu.classList.add('hidden');
                    mobileMenuBtn.setAttribute('aria-expanded', 'false');
                    const icon = mobileMenuBtn.querySelector('i');
                    icon.classList.remove('fa-times');
                    icon.classList.add('fa-bars');
                }
            }
        });
    });

    // Project cards: reachable by mouse, keyboard and assistive tech
    document.querySelectorAll('[data-project]').forEach(card => {
        const projectId = card.getAttribute('data-project');

        card.addEventListener('click', () => openProjectModal(projectId));
        card.addEventListener('keydown', (e) => {
            if (e.key === 'Enter' || e.key === ' ') {
                e.preventDefault();
                openProjectModal(projectId);
            }
        });
    });

    // Modal Close Listeners
    const modal = document.getElementById('projectModal');
    if (modal) {
        // Close modal when clicking outside the content box
        modal.addEventListener('click', function(e) {
            if (e.target === this) {
                closeProjectModal();
            }
        });
    }

    const lightbox = document.getElementById('imageLightbox');
    if (lightbox) {
        // Close lightbox when clicking outside the image
        lightbox.addEventListener('click', function(e) {
            if (e.target === this) {
                closeImageLightbox();
            }
        });
    }

    // Escape closes whichever dialog is on top: the lightbox first, then the project modal
    document.addEventListener('keydown', function(e) {
        if (e.key !== 'Escape') return;
        if (lightbox && !lightbox.classList.contains('hidden')) {
            closeImageLightbox();
        } else if (modal && !modal.classList.contains('hidden')) {
            closeProjectModal();
        }
    });
}

// Setup scroll spy
function setupScrollSpy() {
    const observerOptions = {
        root: null,
        rootMargin: '-20% 0px -70% 0px',
        threshold: 0
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const sectionId = entry.target.getAttribute('data-section');
                updateActiveNavLink(sectionId);
            }
        });
    }, observerOptions);
    
    sections.forEach(section => {
        observer.observe(section);
    });
}

// Update active navigation link
function updateActiveNavLink(sectionId) {
    navLinks.forEach(link => {
        if (link.getAttribute('href') === `#${sectionId}`) {
            link.classList.add('active');
        } else {
            link.classList.remove('active');
        }
    });
    
    currentSection = sectionId;
}

// Initialize mobile menu
function initMobileMenu() {
    if (!mobileMenuBtn || !mobileMenu) return;
    
    function setMobileMenu(open) {
        mobileMenu.classList.toggle('hidden', !open);
        mobileMenuBtn.setAttribute('aria-expanded', open ? 'true' : 'false');

        const icon = mobileMenuBtn.querySelector('i');
        icon.classList.toggle('fa-times', open);
        icon.classList.toggle('fa-bars', !open);

        const langConfig = translations[currentLang] || translations['en'];
        const label = open ? langConfig.closeMenu : langConfig.openMenu;
        if (label) {
            mobileMenuBtn.setAttribute('aria-label', label);
        }
    }

    mobileMenuBtn.addEventListener('click', () => {
        setMobileMenu(mobileMenu.classList.contains('hidden'));
    });

    // Close menu when clicking outside
    document.addEventListener('click', (e) => {
        if (!mobileMenu.contains(e.target) && !mobileMenuBtn.contains(e.target)) {
            setMobileMenu(false);
        }
    });

    // Escape closes the menu and returns focus to the toggle
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && !mobileMenu.classList.contains('hidden')) {
            setMobileMenu(false);
            mobileMenuBtn.focus();
        }
    });
}
// Setup contact form with EmailJS
function setupForm() {
    if (!contactForm) return;
    
    contactForm.addEventListener('submit', function(e) {
        e.preventDefault();
        
        // 1. Get the reCAPTCHA response token
        const captchaResponse = grecaptcha.getResponse();
        
        const t = translations[currentLang] || translations['en'];

        // 2. Validate that the reCAPTCHA is completed before proceeding
        if (captchaResponse.length === 0) {
            alert(t.captchaRequired);
            return;
        }
        
        const nameVal = document.getElementById('name').value;
        const emailVal = document.getElementById('email').value;
        const subjectVal = document.getElementById('subject').value;
        const messageVal = document.getElementById('message').value;
        
        if (!nameVal || !emailVal || !messageVal) {
            alert(t.fieldsRequired);
            return;
        }
        
        const submitBtn = contactForm.querySelector('button[type="submit"]');
        const originalBtnText = submitBtn.innerHTML;
        submitBtn.innerHTML = t.sending + ' <i class="fas fa-spinner fa-spin ms-2" aria-hidden="true"></i>';
        submitBtn.disabled = true;
        
        // 3. Add the reCAPTCHA token to template parameters
        const templateParams = {
            name: nameVal,
            email: emailVal,
            subject: subjectVal,
            message: messageVal,
            'g-recaptcha-response': captchaResponse
        };
        
        emailjs.send('service_aexwb6t', 'template_qpqiteg', templateParams)
            .then(function(response) {
                console.log('SUCCESS!', response.status, response.text);
                
                alert(t.sendSuccess);
                
                contactForm.reset();
                
                // 4. Reset the reCAPTCHA widget for future submissions
                grecaptcha.reset();
                
                submitBtn.innerHTML = originalBtnText;
                submitBtn.disabled = false;
                
            }, function(error) {
                console.log('FAILED...', error);
                
                alert(t.sendError);
                
                submitBtn.innerHTML = originalBtnText;
                submitBtn.disabled = false;
            });
    });
}
// Setup scroll animations
function setupScrollAnimations() {
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.1
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, observerOptions);
    
    sections.forEach(section => {
        observer.observe(section);
    });
}

